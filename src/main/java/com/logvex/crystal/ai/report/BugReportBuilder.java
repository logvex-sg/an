package com.logvex.crystal.ai.report;

import com.logvex.crystal.ai.AISettings;
import com.logvex.crystal.ai.crash.CrashRecord;
import com.logvex.crystal.ai.crash.Diagnosis;
import com.logvex.crystal.ai.privacy.PrivacyFilter;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/**
 * Turns a {@link CrashRecord} plus its {@link Diagnosis} into a sanitized {@link BugReport}.
 *
 * <p>Every field passes through the {@link PrivacyFilter} here, at build time, so the report
 * that is displayed is already the report that would be sent. The builder also enforces the
 * maximum size and refuses to exceed it by truncating the stack trace (never the environment
 * header), so an oversized report cannot be produced.
 *
 * <p>Minecraft-independent and deterministic, so the exact text can be unit tested.
 */
public final class BugReportBuilder {

    private static final String RECIPIENT = "matt.sgrblx@outlook.com";

    private final PrivacyFilter filter;
    private final AISettings settings;

    public BugReportBuilder(PrivacyFilter filter, AISettings settings) {
        this.filter = filter == null ? new PrivacyFilter() : filter;
        this.settings = settings == null ? new AISettings() : settings;
    }

    /** The address reports are addressed to (shown in the UI and the mailto fallback). */
    public static String recipient() {
        return RECIPIENT;
    }

    /** Builds a report for {@code record}, optionally with an AI/rule {@code diagnosis}. */
    public BugReport build(CrashRecord record, Diagnosis diagnosis) {
        List<String> knownNames = knownNames();
        StringBuilder body = new StringBuilder(4096);
        body.append("LOGVEX CRYSTAL bug report\n");
        body.append("=========================\n\n");
        body.append("This report was generated by LOGVEX CRYSTAL. Please review it before sending.\n\n");

        body.append("-- Crash --\n");
        body.append("Fingerprint : ").append(record.fingerprint()).append('\n');
        body.append("Time        : ").append(java.time.Instant.ofEpochMilli(record.timestampMillis())).append('\n');
        body.append("Category    : ").append(record.category().label()).append('\n');
        body.append("Severity    : ").append(record.severity().label()).append('\n');
        body.append("Source      : ").append(record.source()).append('\n');
        body.append("Exception   : ").append(record.exceptionType()).append('\n');
        if (!record.exceptionMessage().isBlank()) {
            body.append("Message     : ").append(record.exceptionMessage()).append('\n');
        }
        if (!record.suspectedModule().isBlank()) {
            body.append("Suspected   : ").append(record.suspectedModule()).append('\n');
        }
        body.append('\n');

        if (settings.includeEnvironment) {
            body.append("-- Environment --\n");
            body.append("Client      : ").append(record.modVersion()).append('\n');
            body.append("Minecraft   : ").append(record.minecraftVersion()).append('\n');
            body.append("Loader      : ").append(record.loaderVersion()).append('\n');
            body.append("Java        : ").append(record.javaVersion()).append('\n');
            body.append("OS          : ").append(record.osName()).append('\n');
            body.append("Baritone    : ").append(record.baritoneStatus()).append('\n');
            body.append("AI          : ").append(record.aiStatus()).append('\n');
            body.append('\n');
        }

        if (diagnosis != null) {
            body.append("-- Diagnosis (").append(diagnosis.confidence().label()).append(") --\n");
            body.append(diagnosis.likelyCause()).append('\n');
            if (!diagnosis.suggestedFixes().isEmpty()) {
                body.append("Suggested fixes:\n");
                for (String fix : diagnosis.suggestedFixes()) {
                    body.append("  - ").append(fix).append('\n');
                }
            }
            if (!diagnosis.hypotheses().isEmpty()) {
                body.append("Notes (unconfirmed):\n");
                for (String h : diagnosis.hypotheses()) {
                    body.append("  - ").append(h).append('\n');
                }
            }
            body.append('\n');
        }

        if (settings.includeLogs && !record.recentEvents().isEmpty()) {
            body.append("-- Recent events --\n");
            for (String event : record.recentEvents()) {
                body.append("  ").append(event).append('\n');
            }
            body.append('\n');
        }

        body.append("-- Stack trace (sanitized) --\n");
        body.append(record.rawStackTrace()).append('\n');

        String sanitized = filter.filter(body.toString(), knownNames);
        sanitized = enforceMaxSize(sanitized, settings.maxReportKilobytes);

        String subject = "LOGVEX CRYSTAL crash report [" + record.category().label() + " / "
                + record.fingerprint() + "]";
        String id = record.fingerprint() + "-" + record.timestampMillis();
        return new BugReport(id, record.fingerprint(), record.timestampMillis(), subject, sanitized,
                BugReport.Status.PENDING, 0, "");
    }

    /** Truncates the report body to the configured maximum, keeping the header intact. */
    static String enforceMaxSize(String body, int maxKilobytes) {
        int maxBytes = Math.max(1, maxKilobytes) * 1024;
        byte[] bytes = body.getBytes(StandardCharsets.UTF_8);
        if (bytes.length <= maxBytes) {
            return body;
        }
        String note = "\n\n[report truncated to " + maxKilobytes + " KB]";
        int keepBytes = Math.max(0, maxBytes - note.getBytes(StandardCharsets.UTF_8).length);
        // Truncating on a byte boundary can split a multi-byte char; decode leniently then trim.
        String kept = new String(bytes, 0, keepBytes, StandardCharsets.UTF_8);
        return kept + note;
    }

    /** Names the caller asked to redact, from the free-text setting. */
    private List<String> knownNames() {
        List<String> names = new ArrayList<>();
        if (settings.extraRedactions != null) {
            for (String line : settings.extraRedactions.split("\\R")) {
                String trimmed = line.trim();
                if (!trimmed.isEmpty()) {
                    names.add(trimmed);
                }
            }
        }
        return names;
    }
}
